const LanguageContext = createContext(null);

function readLanguage() {
  try {
    return localStorage.getItem('t3d:language') === 'ru' ? 'ru' : 'ky';
  } catch {
    return 'ky';
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(readLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem('t3d:language', language);
    } catch {
      // Keep the selected language active for this page when storage is unavailable.
    }
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key, values = {}) => (messages[language][key] || key)
      .replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''))
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}

export function productText(product, field, t) {
  const localized = t(`product.${product.id}.${field}`);
  return localized.startsWith('product.') ? product[field] || '' : localized;
}

export function memoryText(value, t) {
  return String(value).replace(/ГБ/g, t('memory.gb')).replace(/ТБ/g, t('memory.tb'));
}
